import matplotlib.pyplot as plt
import numpy as np

def extraer_metricas(nombre_archivo):
    """Function to extract key metrics from iFogSim console output."""
    energia_cloud = 0.0
    energia_fog = 0.0
    energia_edge_lista = []
    
    latencia_raw = 0.0
    latencia_critica = 0.0
    latencia_response = 0.0
    
    red_total = 0.0

    try:
        with open(nombre_archivo, 'r') as file:
            for linea in file:
                # 1. Extract Energy
                if "cloud : Energy Consumed" in linea:
                    energia_cloud = float(linea.split('=')[1].strip())
                elif "FogServer_Hospital : Energy Consumed" in linea:
                    energia_fog = float(linea.split('=')[1].strip())
                elif "Edge_Paciente_" in linea and "Energy Consumed" in linea:
                    energia_edge_lista.append(float(linea.split('=')[1].strip()))
                
                # 2. Extract Tuple Latency (ms)
                elif "RAW_DATA --->" in linea:
                    latencia_raw = float(linea.split('--->')[1].strip())
                elif "Crítica --->" in linea:
                    latencia_critica = float(linea.split('--->')[1].strip())
                elif "RESPONSE --->" in linea:
                    latencia_response = float(linea.split('--->')[1].strip())
                    
                # 3. Extract Network Usage (Bytes)
                elif "Total network usage" in linea:
                    red_total = float(linea.split('=')[1].strip())
                    
    except FileNotFoundError:
        print(f"Error: File '{nombre_archivo}' not found. Ensure both simulations are executed.")
        return None

    energia_edge_promedio = sum(energia_edge_lista) / len(energia_edge_lista) if energia_edge_lista else 0.0

    return {
        "energia": [energia_cloud, energia_fog, energia_edge_promedio],
        "latencia": [latencia_raw, latencia_critica, latencia_response],
        "red": red_total
    }

# 1. Read the two text files generated by Java
datos_nuestra = extraer_metricas("salida_consola.txt")
datos_edgewards = extraer_metricas("salida_consola_edgewards.txt")

if datos_nuestra and datos_edgewards:
    x = np.arange(3)  # X-axis positions
    width = 0.35      # Bar width

    # ==========================================
    # FIGURE 1: Tuple Latency Comparison
    # ==========================================
    fig, ax = plt.subplots(figsize=(9, 5))
    tuplas = ['RAW_DATA\n(Normal)', 'Critical\n(Anomaly)', 'RESPONSE\n(Alarm)']

    rects1 = ax.bar(x - width/2, datos_edgewards["latencia"], width, label='Baseline (Edgewards)', color='#A9A9A9')
    rects2 = ax.bar(x + width/2, datos_nuestra["latencia"], width, label='Proposed Heuristic (CriticalityAware)', color='#B22222')

    ax.set_ylabel('Delay Time / Latency (ms)', fontsize=12)
    ax.set_title('Tuple Latency Comparison', fontsize=14, fontweight='bold')
    ax.set_xticks(x)
    ax.set_xticklabels(tuplas)
    ax.legend()
    ax.grid(axis='y', linestyle='--', alpha=0.7)

    # Bar labels
    ax.bar_label(rects1, padding=3, fmt='%.2f ms', fontweight='bold')
    ax.bar_label(rects2, padding=3, fmt='%.2f ms', fontweight='bold')

    plt.tight_layout()
    plt.savefig('graph_1_latency_comparison.png', dpi=300)
    plt.close()

    # ==========================================
    # FIGURE 2: Energy Consumption Comparison
    # ==========================================
    fig, ax = plt.subplots(figsize=(9, 5))
    entidades = ['Cloud\n(Tier 4)', 'Fog Server\n(Tier 3)', 'Edge Average\n(Tier 2)']

    rects1 = ax.bar(x - width/2, datos_edgewards["energia"], width, label='Baseline (Edgewards)', color='#778899')
    rects2 = ax.bar(x + width/2, datos_nuestra["energia"], width, label='Proposed Heuristic (CriticalityAware)', color='#D2691E')

    ax.set_ylabel('Energy Consumed (W*s)', fontsize=12)
    ax.set_title('Energy Consumption Comparison by Tier', fontsize=14, fontweight='bold')
    ax.set_xticks(x)
    ax.set_xticklabels(entidades)
    ax.legend()
    ax.grid(axis='y', linestyle='--', alpha=0.7)

    ax.bar_label(rects1, padding=3, fmt='%d', fontweight='bold')
    ax.bar_label(rects2, padding=3, fmt='%d', fontweight='bold')

    plt.tight_layout()
    plt.savefig('graph_2_energy_comparison.png', dpi=300)
    plt.close()

    # ==========================================
    # FIGURE 3: Network Usage Comparison (Trade-off)
    # ==========================================
    fig, ax = plt.subplots(figsize=(7, 5))
    politicas = ['Baseline\n(Edgewards)', 'Proposed Heuristic\n(CriticalityAware)']
    valores_red = [datos_edgewards["red"], datos_nuestra["red"]]

    barras = ax.bar(politicas, valores_red, color=['#4682B4', '#2E8B57'], width=0.45)
    ax.set_ylabel('Network Usage (Bytes)', fontsize=12)
    ax.set_title('Network Bandwidth Usage Comparison', fontsize=14, fontweight='bold')
    ax.grid(axis='y', linestyle='--', alpha=0.7)

    ax.bar_label(barras, padding=3, fmt='%d Bytes', fontweight='bold')

    plt.tight_layout()
    plt.savefig('graph_3_network_comparison.png', dpi=300)
    plt.close()

    print("Comparative evaluation graphs generated successfully in English (300 dpi)!")
